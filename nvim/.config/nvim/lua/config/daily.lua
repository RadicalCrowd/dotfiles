-- ==============================================================================
-- Obsidian Daily Note Manager (Obsidian Plugin Parity)
-- Handles opening today's daily note or generating a new one from template
-- ==============================================================================

local M = {}

---Get the canonical RadicallyInsane vault directory
---@return string
function M.get_vault_dir()
  return vim.fn.expand("~/Obsidian-Vaults/RadicallyInsane")
end

---Get current date components
---@return table
function M.get_today_info()
  return {
    year = os.date("%Y"),
    month = os.date("%m"),
    day = os.date("%d"),
    date = os.date("%Y-%m-%d"),
  }
end

---Get expected path for today's daily note
---@return string
function M.get_today_path()
  local vault = M.get_vault_dir()
  local info = M.get_today_info()
  return string.format("%s/01-Periodic/%s/Daily/%s/%s.md", vault, info.year, info.month, info.date)
end

---Generate a new daily note from the vault template
---@param path string
function M.create_daily_note(path)
  local vault = M.get_vault_dir()
  local info = M.get_today_info()
  local template_path = vault .. "/01-Periodic/Templates/Daily.md"

  local content = {}
  if vim.fn.filereadable(template_path) == 1 then
    local lines = vim.fn.readfile(template_path)
    for _, line in ipairs(lines) do
      -- Replace Templater syntax tags <% tp.date.now(...) %> and <% tp.file.title %>
      local parsed = line:gsub("<%%.-tp%.date%.now%b().-%%>", info.date)
      parsed = parsed:gsub("<%%.-tp%.file%.title.-%%>", info.date)
      table.insert(content, parsed)
    end
  else
    content = {
      "---",
      "type: daily",
      "status: active",
      "tags:",
      "  - daily",
      "date: " .. info.date,
      "---",
      "",
      "# Daily Note — " .. info.date,
      "",
      "[[moc|Map of Content]] · [[CODE|CODE Dashboard]] · [[00-Inbox/README|Inbox]]",
      "",
      "> **Capture at the bottom, journal at the top.** Rants go in §3. The agent distills §3 into §2.",
      "",
      "## 1. TODO — Today",
      "<!-- Generated by `distill.py today` from <entity>/todo.md. -->",
      "",
      "## 2. Journal",
      "- **<Project / Area>** — ",
      "",
      "## 3. Raw Capture",
      "- ",
    }
  end

  local dir = vim.fn.fnamemodify(path, ":p:h")
  if vim.fn.isdirectory(dir) == 0 then
    vim.fn.mkdir(dir, "p")
  end

  vim.fn.writefile(content, path)
  vim.notify("Created daily note: " .. info.date .. ".md", vim.log.levels.INFO)
end

---Open today's daily note, creating it from template if not yet generated
function M.open_daily_note()
  local today_path = M.get_today_path()
  if vim.fn.filereadable(today_path) == 0 then
    M.create_daily_note(today_path)
  end

  vim.cmd("edit " .. vim.fn.fnameescape(today_path))
end

---Open the latest existing daily note in the vault
function M.open_latest_daily_note()
  local vault = M.get_vault_dir()
  local glob_pattern = string.format("%s/01-Periodic/**/Daily/**/*.md", vault)
  local files = vim.fn.glob(glob_pattern, true, true)
  if #files > 0 then
    table.sort(files)
    local latest = files[#files]
    vim.cmd("edit " .. vim.fn.fnameescape(latest))
  else
    M.open_daily_note()
  end
end

return M
